package cm.amcloud.platform.reservation.model;

import java.time.LocalDateTime;
import java.util.Date;

import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import lombok.Data;

@Entity
@Data
public class Reservation {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    private String travelerName;
    private String destination;
    private String agencyName;
    private String depart;
    private LocalDateTime heureDepart;
    private String classe;
    private Date dateReservation;
    private String status; // "CONFIRMED", "CANCELED", "PENDING"
    private String paymentMethod; // "CASH", "CARD", "ONLINE"
    private String seatNumber; // Optional, if seat selection is available
  
    // Getters and Setters can be generated by Lombok @Data annotation
    // or you can manually define them if needed
    public Reservation() {
        // Default constructor
    }
    public Reservation(String travelerName, String destination, String agencyName, String depart, LocalDateTime heureDepart, String classe) {
        this.travelerName = travelerName;
        this.destination = destination;
        this.agencyName = agencyName;
        this.depart = depart;
        this.heureDepart = heureDepart;
        this.classe = classe;
        this.dateReservation = new Date();
        this.status = "PENDING"; // Default status
    }
   protected String getStatus() {
        return status;
    }

    protected void setStatus(String status) {
        this.status = status;
    }

    protected String getPaymentMethod() {
        return paymentMethod;
    }

    protected void setPaymentMethod(String paymentMethod) {
        this.paymentMethod = paymentMethod;
    }

    protected String getSeatNumber() {
        return seatNumber;
    }

    protected void setSeatNumber(String seatNumber) {
        this.seatNumber = seatNumber;
    }
    @Override
    public String toString() {
        return "Reservation{" +
                "id=" + id +
                ", travelerName='" + travelerName + '\'' +
                ", destination='" + destination + '\'' +
                ", agencyName='" + agencyName + '\'' +
                ", depart='" + depart + '\'' +
                ", heureDepart=" + heureDepart +
                ", classe='" + classe + '\'' +
                ", dateReservation=" + dateReservation +
                ", status='" + status + '\'' +
                ", paymentMethod='" + paymentMethod + '\'' +
                ", seatNumber='" + seatNumber + '\'' +
                '}';
    }
}

